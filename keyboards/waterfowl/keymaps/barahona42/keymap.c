void master_oled_display(void) {
    oled_write_P(PSTR("Layer:"), false);
    switch (get_highest_layer(layer_state | default_layer_state)) {
        case BASE:
            oled_write_P(PSTR("BASE\n"), false);
            return;
        case LAY1:
            oled_write_P(PSTR("LAY1\n"), false);
            return;
        case LAY2:
            oled_write_P(PSTR("LAY2\n"), false);
            return;
        case LAY3:
            oled_write_P(PSTR("LAY3\n"), false);
            return;
        case CONF:
            oled_write_P(PSTR("CONF\n"), false);
            return;
    }
    if (get_mods() & MOD_BIT(KC_LGUI)) {
        oled_write_P(PSTR("LGUI ON\n"), false);
    }
}

void secondary_oled_display() {
    master_oled_display();
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        master_oled_display();
    } else {
        secondary_oled_display();
    }
    return false;
}
